"""Дизайнер: придумывает визуал каждой из 9 панелей и собирает промпт мастер-кадра.

Решает, что в кадре на каждой панели (предмет, сцена, свет, акцент).
Тренды подсматриваем в отобранных пинах.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import config, llm

_SCHEMA = {
    "type": "object",
    "properties": {
        "series_look": {"type": "string"},
        "panels": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "n": {"type": "integer"},
                    "scene": {"type": "string"},
                    "accent": {"type": "string"},
                },
                "required": ["n", "scene", "accent"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["series_look", "panels"],
    "additionalProperties": False,
}

_PROMPT = """Ты арт-директор карусели из 9 панелей. Тема дня: {theme}, сегмент: {segment},
контент-семья: {family}.

Придумай визуал для 9 панелей. У каждой свой предметный кадр под её заголовок.
Панели - одна серия: общий фон, свет и типографика, меняются предмет и композиция.

Заголовки панелей:
{heads}

Требования (STYLE-DNA):
- каждый кадр - плёночная фотография: живой свет из окна, настоящие фактуры
  (дерево, ткань, металл с потёртостями, капли, пыль), зерно Kodak Portra.
  Не 3D-рендер, не CGI, не глянцевый пластик, не выкладка на постаменте;
- сцена как случайный кадр из Pinterest: предмет в живой обстановке
  (стол, руки-кроп, ткань, зеркало), не по центру кадра;
- свет по умолчанию светлый дневной; тёмный кадр только если чистый глянец с бликом,
  без мутной черноты;
- один акцентный цвет на панель;
- предмет из мира сегмента (инструмент, флакон без лейбла, ткань, украшение без лого,
  чашка, ноутбук, кресло). Никаких людей, лиц и фигур;
- предмет не перекрывает текст: нижняя треть или бок;
- никаких логотипов, брендов, надписей внутри предмета, английских слов;
- предметы разные на всех девяти панелях;
- панель 9 (призыв) самая пустая, только акцентная деталь.

scene - одно предложение по-русски: что в кадре, где стоит, как освещено.
accent - цвет акцента этой панели одним словом.
series_look - 1-2 предложения об общем виде серии (фон, свет, шрифт).

{trends}"""


def design_panels(theme: dict, heads: list[str], out_file: Path,
                  pins_note: str = "") -> dict:
    trends = (f"Тренды из свежих пинов Pinterest (учти фактуры и цвета): {pins_note}"
              if pins_note else "")
    learned = config.extra_rules("Визуал")
    if learned:
        trends += "\n\nВыученные правила (обязательны):\n" + learned

    heads_txt = "\n".join(f"  панель {i + 1}: «{h}»" for i, h in enumerate(heads))
    result = llm.structured(
        [{"type": "text", "text": _PROMPT.format(
            theme=theme["name"], segment=theme["segment"], family=theme["family"],
            heads=heads_txt, trends=trends)}],
        _SCHEMA,
        max_tokens=4000,
    )
    if len(result["panels"]) != 9:
        raise RuntimeError(f"Дизайнер вернул {len(result['panels'])} панелей вместо 9")
    out_file.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    return result


def build_master_prompt(design: dict, heads: list[str]) -> str:
    """Финальный промпт мастер-кадра: сетка 3×3, дословные заголовки, сцены дизайнера."""
    panels = []
    for i, head in enumerate(heads):
        p = next((x for x in design["panels"] if x["n"] == i + 1), None)
        scene = p["scene"] if p else "минималистичный тёмный фон с бликом света"
        accent = p["accent"] if p else "золото"
        panels.append(f"панель {i + 1}: заголовок «{head}»; кадр: {scene}; акцент: {accent}")

    return (
        "Одно изображение - сетка ровно 3 колонки x 3 ряда, 9 равных панелей "
        "без рамок, без разделителей и без белых линий между ними.\n"
        f"Общий вид серии: {design['series_look']}\n"
        "ФОТОРЕАЛИЗМ ОБЯЗАТЕЛЕН: каждая панель - настоящая плёночная фотография "
        "(35 мм, Kodak Portra, зерно, естественный свет, реальные фактуры и мелкие "
        "несовершенства, малая глубина резкости). НЕ 3D-рендер, НЕ CGI, НЕ пластиковый "
        "глянец, НЕ студийный продуктовый рендер, НЕ векторная иллюстрация.\n"
        "ТИПОГРАФИКА: жирный узкий гротеск ЗАГЛАВНЫМИ буквами, крупно - заголовок "
        "занимает 2-4 строки и примерно треть высоты панели; одно слово или число "
        "выделено золотым акцентом, остальной текст белый. Текст в безопасной зоне "
        "(отступ 12% от краёв панели), предмет не перекрывает буквы, вокруг текста воздух.\n"
        "Тексты панелей ДОСЛОВНО, без изменений, без добавленных слов и без нумерации:\n"
        + "\n".join(panels)
        + "\nНикаких логотипов, водяных знаков, английских слов, случайных надписей, "
        "номеров страниц и подписей. Кириллица идеально читаемая, буквы не искажены."
        + (("\nВыученные правила (обязательны): "
            + config.extra_rules("Визуал").replace("\n", " "))
           if config.extra_rules("Визуал") else "")
    )
